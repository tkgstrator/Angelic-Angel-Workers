test('exhausted deliveries remain as redacted dead letters and can be retried', { timeout: 20000 }, () => withRuntime(async (ctx) => {
  await registerAndStart(ctx)
  await ctx.control({ command: 'options', options: { webhookFailures: 80 } })
  await ctx.control({ command: 'notify', version: 'dead/letter', text: '{"private":"hidden-notification-body"}' })
  const storage = await ctx.storage()
  await eventually(() => storage.exec("SELECT attempts FROM outbox WHERE version = 'dead/letter'"), (rows) => rows[0]?.attempts === 1)
  await storage.exec("UPDATE outbox SET attempts = 7, next_at = ? WHERE version = 'dead/letter'", Date.now() - 1)
  await ctx.stub.ensure()
  await eventually(ctx.status, (s) => s.outbox?.dead === 1)
  const dead = await ctx.api('deadletters')
  assert.equal(dead.status, 200)
  const listing = await dead.text()
  assert.ok(listing.includes('dead/letter'))
  assert.ok(!listing.includes('hidden-notification-body'))
  await ctx.control({ command: 'options', options: { webhookFailures: 0 } })
  assert.equal((await ctx.api('retry-deadletters', 'POST')).status, 200)
  await eventually(ctx.status, (s) => s.outbox?.dead === 0 && s.outbox?.pending === 0)
  assert.equal((await ctx.control()).deliveries.at(-1).status, 200)
}))

