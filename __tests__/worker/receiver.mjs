test('temporary SQLite acceptance failures close the socket without ACK or dedupe success', { timeout: 20000 }, () => withRuntime(async (ctx) => {
  await registerAndStart(ctx)
  const storage = await ctx.storage()
  await storage.exec("CREATE TRIGGER fail_accept BEFORE INSERT ON outbox BEGIN SELECT RAISE(ABORT, 'temporary storage failure'); END")
  await ctx.control({ command: 'notify', version: 'storage/failure' })
  const snapshot = await eventually(() => ctx.control(), (s) => !s.socket)
  assert.equal(acknowledgments(snapshot).length, 0)
  assert.equal(snapshot.pending, 1)
  const rows = await storage.exec("SELECT COUNT(*) AS n FROM outbox WHERE version = 'storage/failure'")
  assert.equal(rows[0].n, 0)
  await storage.exec('DROP TRIGGER fail_accept')
}))

