import { test } from 'node:test'
import assert from 'node:assert/strict'
import { withRuntime, eventually, registerAndStart } from './harness.js'

const acknowledgments = (snapshot) => snapshot.frames.filter((f) => f.messageType === 'ack').flatMap((f) => f.updates)

test('register, resume, decrypt both formats, ACK and deliver exact JSON without leaking secrets', { timeout: 30000 }, () => withRuntime(async (ctx) => {
  await registerAndStart(ctx)
  const text = '{ "title": "日本語", "id": 9007199254740993 }'
  await ctx.control({ command: 'notify', text, version: 'opaque/modern' })
  await ctx.control({ command: 'notify', text, version: 'opaque/legacy', encoding: 'aesgcm' })
  const snapshot = await eventually(() => ctx.control(), (s) => s.deliveries.length === 2 && acknowledgments(s).length === 2)
  assert.deepEqual(snapshot.deliveries.map((d) => d.body), [text, text])
  assert.deepEqual(acknowledgments(snapshot).map((a) => a.code), [100, 100])
  assert.equal(snapshot.xRequests[0].headers.cookie, 'auth_token=AUTH_TEST_SECRET; ct0=CT0_TEST_SECRET')
  const status = await ctx.api('status')
  const body = await status.text()
  for (const secret of ['AUTH_TEST_SECRET', 'CT0_TEST_SECRET', snapshot.xRequests[0].body.push_device_info.encryption_key2, snapshot.xRequests[0].body.push_device_info.token, 'privateKey']) assert.ok(!body.includes(secret), secret)
  assert.equal(status.headers.get('cache-control'), 'no-store')
}))

